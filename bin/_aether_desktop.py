def adapted_bar(base, monitor):
    """Keep each action, grouping optional tools only on narrow logical outputs."""
    config = copy.deepcopy(base)
    config['output'] = monitor['name']
    width = monitor.get('height' if monitor.get('transform', 0) % 2 else 'width', 1920)
    width /= monitor.get('scale', 1) or 1
    if width >= 2000:
        return config
    right = list(config.get('modules-right', []))
    groups = {
        'tools': ['custom/calc', 'custom/opencam', 'bluetooth', 'custom/vrdesk'],
        'system': ['cpu', 'custom/gpu', 'memory', 'battery'],
    }
    for name, candidates in groups.items():
        members = [module for module in right if module in candidates]
        if not members:
            continue
        position = min(right.index(module) for module in members)
        right = [module for module in right if module not in members]
        right.insert(position, 'group/' + name)
        config['custom/' + name] = {
            'format': name.title(),
            'tooltip-format': 'Click to show or hide ' + name + '. Also available through the application launcher.',
        }
        config['group/' + name] = {
            'orientation': 'inherit',
            'drawer': {'click-to-reveal': True, 'transition-duration': 0,
                       'transition-left-to-right': False},
            'modules': ['custom/' + name, *members],
        }
    config['modules-right'] = right
    config.setdefault('hyprland/window', {})['max-length'] = 18 if width >= 1200 else 8
    config.setdefault('clock', {})['format'] = '{:%H:%M}'
    # No status/health or remote-control indicator is hidden inside a drawer.
    return config


def bar_config_path():
    source = Path.home() / '.config/waybar/config.jsonc'
    # The owned template uses standalone // comments. If a user supplies other
    # JSONC extensions, leave parsing to Waybar instead of rewriting their file.
    try:
        base = json.loads(re.sub(r'^\s*//.*$', '', source.read_text(), flags=re.M))
        if not isinstance(base, dict):
            return str(source)
        result = subprocess.run(['hyprctl', 'monitors', '-j'], capture_output=True,
                                text=True, check=True, timeout=1)
        monitors = [monitor for monitor in json.loads(result.stdout)
                    if not monitor['name'].startswith(('VIRT-', 'VR-')) and not monitor.get('disabled')]
        if not monitors:
            return str(source)
        config = [adapted_bar(base, monitor) for monitor in monitors]
    except (OSError, ValueError, KeyError, subprocess.SubprocessError):
        return str(source)
    runtime = Path(os.environ.get('XDG_RUNTIME_DIR', str(Path.home() / '.cache')))
    signature = hashlib.sha256(os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', 'default').encode()).hexdigest()[:12]
    destination = runtime / f'instrument-score-waybar-{signature}.json'
    # Runtime files contain only the user's existing bar config, not window data.
    descriptor, temporary = tempfile.mkstemp(prefix=destination.name + '.', dir=runtime)
    try:
        with os.fdopen(descriptor, 'w') as stream:
            json.dump(config, stream, indent=2)
            stream.write('\n')
        os.replace(temporary, destination)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return str(destination)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("adapter", choices=("waybar", "waybar-config", "kitty", "qt", "compositor", "apply-compositor"))
    args = parser.parse_args()
    if args.adapter == "apply-compositor":
        result = subprocess.run(["hyprctl", "eval", compositor_lua()],
                                text=True, capture_output=True, timeout=2, check=True)
        if result.stderr.strip():
            raise RuntimeError(result.stderr.strip())
        print(result.stdout.strip())
    elif args.adapter == 'waybar-config':
        print(bar_config_path())
    else:
        print({"waybar": waybar_css, "kitty": kitty_conf, "qt": qt_palette, "compositor": compositor_lua}[args.adapter](), end="")
