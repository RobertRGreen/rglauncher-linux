def enable_animations(text: str) -> str:
    """Change only the GTK Settings key, preserving comments and other settings."""
    section = re.search(r'^\[Settings\][ \t]*\r?\n', text, re.M)
    if not section:
        return text + ('\n' if text and not text.endswith('\n') else '') + '[Settings]\ngtk-enable-animations=true\n'
    end = re.search(r'^\[', text[section.end():], re.M)
    stop = section.end() + end.start() if end else len(text)
    body = text[section.end():stop]
    key = r'^gtk-enable-animations\s*=.*$'
    if re.search(key, body, re.M):
        body = re.sub(key, 'gtk-enable-animations=true', body, flags=re.M)
    else:
        body = 'gtk-enable-animations=true\n' + body
    return text[:section.end()] + body + text[stop:]


def write_preserving(path: Path, content: str) -> None:
    """Back up changes and atomically replace; unchanged launches do no writes."""
    if path.is_symlink():
        raise RuntimeError(f'Refusing to replace symlink: {path}')
    if path.exists() and path.read_text() == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        shutil.copy2(path, path.with_name(path.name + f'.before-cyber-{time.time_ns()}'))
    fd, temporary = tempfile.mkstemp(prefix=f'.{path.name}.', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        os.chmod(temporary, path.stat().st_mode & 0o777 if path.exists() else 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


