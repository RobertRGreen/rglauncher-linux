# Confirmed by the supervisor's GTK gi widget-tree probes (2026-09-13).
# Plain popout windows use the `window` node, never either of these roots.
# The three custom Gtk.Dialog subclasses need explicit exclusions at USER priority.
GTK3_DIALOG_ROOTS = (
    'dialog:not(.wifi-pass):not(.bt-pass):not(.rgb-pickdlg)',
    'messagedialog',
)
GTK4_DIALOG_ROOTS = ('window.dialog',)


def secondary_text() -> str:
    """Mix tokens in sRGB; no separate palette or literal font/color values."""
    # Opaque secondary role; never dim an entire label layer.
    # The current semantic secondary token is readable; this mix is legacy-compatible.
    channels = [round((a + b) / 2) for a, b in
                zip(rgb_channels(MUTED), rgb_channels(ACCENT2))]
    return 'rgb({},{},{})'.format(*channels)


def build_dialog_css(major: int) -> str:
    """Expand every selector through the verified roots; no GTK3 scope escapes.

    GTK CSS cannot uppercase application-owned labels. Keep localized labels and
    mnemonics intact; heading fonts and tracking provide the available treatment.
    GTK3 TreeView cell renderers have no per-column CSS nodes, so secondary file
    columns cannot be singled out with CSS. GTK4 exposes actual cell nodes.
    """
    roots = GTK3_DIALOG_ROOTS if major == 3 else GTK4_DIALOG_ROOTS
    blocks = ['\n/* System dialogs: static effects, scoped away from GTK3 popouts. */\n']

    def rule(suffixes, declarations):
        selectors = [root + (' ' + suffix if suffix else '')
                     for root in roots for suffix in suffixes]
        blocks.append(',\n'.join(selectors) + ' {\n    ' + declarations + '\n}\n')

    secondary = secondary_text()
    transition = ('transition: background-color 150ms ease-out, color 150ms ease-out, '
                  'border-color 150ms ease-out, box-shadow 150ms ease-out;')
    glow = f'{GLASS_INSET}, 0 0 5px {rgba(PURPLE, .18)}, 0 0 14px {rgba(PURPLE, .10)}'
    rule(('',), f'background-color: {BG}; background-image: linear-gradient(135deg, {rgba(PURPLE, .05)}, transparent 65%); '
         f'color: {FG}; font-family: "{FONT_BODY}"; border-radius: 8px;')
    # Do not blanket-reset descendants: color/font chooser previews must retain
    # their sample colors and fonts. Reset only the working-surface nodes.
    rule(('decoration',) if major == 3 else ('',),
         f'border: 1px solid {PURPLE}; border-radius: 8px; box-shadow: {glow};')
    rule(('headerbar', '.titlebar', '.dialog-action-area', '.dialog-action-box'),
         f'background-color: {BG_CARD}; background-image: none; color: {FG}; '
         'border-radius: 0;')
    rule(('headerbar', '.titlebar'), f'border-bottom: 1px solid {PURPLE};')
    rule(('headerbar .title', '.titlebar .title'),
         f'font-family: "{FONT_HEAD}"; color: {FG}; letter-spacing: 1px; '
         + chromatic_shadow())
    rule(('.dim-label', 'label.subtitle'), f'color: {secondary}; opacity: 1;')
    rule(('entry', 'spinbutton'),
         f'background-color: {BG_CARD}; background-image: none; border: 1px solid {CONTROL_LINE}; '
         f'border-radius: 8px; color: {FG}; caret-color: {ACCENT2}; '
         f'box-shadow: {GLASS_INSET}; ' + transition)
    rule(('entry:focus', 'spinbutton:focus') if major == 3 else
         ('entry:focus-within', 'spinbutton:focus-within'),
         f'border-color: {ACCENT2}; box-shadow: {GLASS_INSET}, 0 0 6px {rgba(ACCENT2, .22)};')
    if major == 4:
        rule(('entry text', 'spinbutton text'), f'color: {FG}; caret-color: {ACCENT2};')
    rule(('button',),
         f'background-color: transparent; background-image: none; color: {FG}; '
         f'border: 1px solid {CONTROL_LINE}; border-radius: 8px; '
         f'font-family: "{FONT_BODY}"; letter-spacing: 1px; text-shadow: none; '
         'box-shadow: none; ' + transition)
    rule(('button:hover', 'button:focus'),
         f'background-color: {BG_HOT}; border-color: {ACCENT2}; color: {ACCENT2}; '
         f'box-shadow: 0 0 5px {rgba(ACCENT2, .18)};')
    for action, color in (('suggested-action', ACCENT2), ('destructive-action', DANGER)):
        rule((f'button.{action}',), f'border-color: {color}; color: {color};')
        rule((f'button.{action}:hover', f'button.{action}:active'),
             f'background-color: {color}; color: {BG}; border-color: {color}; '
             f'box-shadow: 0 0 6px {rgba(color, .22)};')
    rule(('button label',), 'color: inherit;')
    rule(('button:disabled', 'entry:disabled'),
         f'background-color: {BG_CARD}; color: {secondary}; border-color: {LINE}; '
         'box-shadow: none; text-shadow: none;')
    rule(('button:focus', 'entry:focus', 'checkbutton:focus', 'switch:focus'),
         f'outline: 2px solid {PURPLE}; outline-offset: 2px;')

    views = ('treeview.view', 'list', 'stack.view') if major == 3 else (
        'columnview', 'listview.view', 'list', 'stack.view')
    rule(views, f'background-color: {BG}; background-image: none; color: {FG};')
    hover = ('treeview.view:hover', 'row:hover') if major == 3 else ('row:hover',)
    selected = ('treeview.view:selected', 'row:selected') if major == 3 else ('row:selected',)
    rule(hover, f'background-color: {BG}; '
         f'background-image: linear-gradient({rgba(PURPLE, .08)}, {rgba(PURPLE, .08)});')
    rule(selected, f'background-color: {BG_HOT}; background-image: none; color: {ACCENT2}; '
         f'box-shadow: inset 3px 0 {ACCENT2}; text-shadow: none;')
    if major == 4:
        rule(('filechooser columnview row cell:not(:first-child)',), f'color: {secondary};')
        rule(('row:selected cell', 'row:selected label'), f'color: {ACCENT2};')
    rule(('placessidebar', 'placessidebar list'),
         f'background-color: {BG_CARD}; background-image: none; color: {FG};')
    rule(('placessidebar',), f'border-right: 1px solid {PURPLE};')
    rule(('placessidebar row:selected', 'placessidebar row:selected .sidebar-label',
          'placessidebar row:selected .sidebar-icon'), f'color: {ACCENT2};')
    pathbar = 'filechooser #pathbarbox' if major == 3 else 'filechooser pathbar'
    rule((pathbar,), f'background-color: {BG_CARD}; background-image: none;')
    rule((pathbar + ' button',), f'font-family: "{FONT_BODY}";')
